def masks(p):
    on = acc = gh = 0
    for i, ch in enumerate(p):
        if ch in "Xxg": on |= 1 << i
        if ch == "X": acc |= 1 << i
        if ch == "g": gh |= 1 << i
    return on, acc, gh

lines = []
lines.append("// Generated by tools/gen_patterns.py - edit the list there, not this file.")
lines.append("#pragma once")
lines.append("")
lines.append("enum { kNumPatternGroups = %d, kNumPatterns = %d };" % (len(G), sum(len(g[1]) for g in G)))
lines.append("static const char* const kPatternGroupNames[kNumPatternGroups + 1] = {")
for g in G: lines.append('    "%s",' % g[0])
lines.append("    0};")
starts, idx = [], 0
for g in G:
    starts.append(idx); idx += len(g[1])
lines.append("static const uint8_t kPatternGroupStart[kNumPatternGroups + 1] = {%s};" % ", ".join(str(s) for s in starts + [idx]))
lines.append("// name, steps, stepTicks, cycleTicks, onsets, accents, ghosts, swing")
lines.append("static const PatternDef kPatterns[kNumPatterns] = {")
for gi, g in enumerate(G):
    lines.append("    // %s" % g[0])
    for name, st, p, sw in g[1]:
        assert len(p) <= 16, name
        on, acc, gh = masks(p)
        lines.append('    {"%s", %d, %d, %d, 0x%04x, 0x%04x, 0x%04x, %d},  // %s' % (name, len(p), st, len(p) * st, on, acc, gh, sw, p))
lines.append("};")
out = os.path.join(os.path.dirname(__file__), "..", "src", "patterns.h")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out, idx, "patterns in", len(G), "groups")
